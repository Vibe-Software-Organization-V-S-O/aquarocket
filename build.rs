extern crate cbindgen;

use std::env;
use std::path::PathBuf;

fn main() {
    let crate_dir = env::var("CARGO_MANIFEST_DIR").unwrap();
    let package_name = env::var("CARGO_PKG_NAME").unwrap();

    let output_file = PathBuf::from(&crate_dir).join(format!("{}.h", package_name));

    cbindgen::Builder::new()
        .with_crate(crate_dir)
        .with_language(cbindgen::Language::C)
        .with_include_guard("AQUAROCKET_H")
        .with_autogen_warning("/* Generated by cbindgen - DO NOT EDIT MANUALLY */")
        .generate()
        .map(|config| config.write_to_file(output_file))
        .unwrap_or_else(|e| {
            eprintln!("Warning: Failed to generate C bindings: {:?}", e);
            true
        });
}
